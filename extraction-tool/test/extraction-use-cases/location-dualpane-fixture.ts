/** Loads a typed fixture model from the shared fixture tree. */
export function loadTypedFixtureModel(path: string): FixtureModel {
	return toFixtureModel(loadFixtureModel(path));
}

/** Converts a generic fixture to the local test fixture shape. */
export function toFixtureModel(model: GenericModel): FixtureModel {
	return { ...(model as FixtureModel), path: `${(model as FixtureModel).header.id}.json` };
}

/** Returns model header annotations. */
export function annotationsOf(model: FixtureModel): readonly ModelAnnotation[] {
	return (model.header.annotations ?? []).filter(isModelAnnotation);
}

/** Returns model header references. */
export function modelReferencesOf(model: FixtureModel): readonly ModelReference[] {
	return (model.header.modelReferences ?? []).filter(isModelReference);
}

/** Parses bindingConfiguration annotation JSON. */
export function parseBindings(value: string | undefined): readonly BindingConfiguration[] {
	const parsedValue = value === undefined ? [] : (JSON.parse(value) as unknown);

	return Array.isArray(parsedValue) ? parsedValue.filter(isBindingConfiguration) : [];
}

/** Returns header refs matching the requested purpose. */
export function headerRefsWithPurpose(model: FixtureModel, purpose: string): readonly string[] {
	return modelReferencesOf(model).flatMap((reference) =>
		reference.purpose === purpose && typeof reference.reference === "string" ? [reference.reference] : []
	);
}

/** Returns the extracted component object. */
export function getComponent(model: FixtureModel): Record<string, unknown> {
	const component = isRecord(model.content) ? model.content.component : undefined;

	return isRecord(component) ? component : {};
}

/** Returns row action event names from an overview model. */
export function getRowActionEvents(model: FixtureModel): readonly string[] {
	return getRowActions(model).flatMap((action) =>
		isRecord(action) && typeof action.event === "string" ? [action.event] : []
	);
}

/** Returns raw row action entries from an overview model. */
export function getRowActions(model: FixtureModel): readonly unknown[] {
	const rowActionGroup = isRecord(model.content) ? model.content.rowActionGroup : undefined;

	return isRecord(rowActionGroup) && Array.isArray(rowActionGroup.actions) ? rowActionGroup.actions : [];
}

/** Requires an optional value in test setup code. */
export function requireModel<Model>(model: Model | undefined, description: string): Model {
	if (model === undefined) {
		throw new Error(`Expected ${description} to be present`);
	}

	return model;
}

/** Type guard: true if and only if value is a non-null object. Imported from fixture-utils. */
export { isRecord };

export function createLocationOnlyFormModel(): GenericModel {
	const formModel = structuredClone(loadFixtureModel(FORM_FIXTURE_PATH)) as MutableFixtureModel;
	const bindingConfiguration = parseBindings(annotationValue(formModel, "bindingConfiguration")).filter(
		(binding) => binding.details?.name === LOCATION_BINDING_NAME || binding.details?.relationshipName === "Location"
	);

	formModel.header.annotations = annotationsOf(formModel as FixtureModel).map((annotation) =>
		annotation.name === "bindingConfiguration"
			? { ...annotation, value: JSON.stringify(bindingConfiguration) }
			: annotation
	);
	formModel.header.modelReferences = modelReferencesOf(formModel as FixtureModel).filter(
		(reference) => reference.reference !== "PostAddressLinks-overview"
	);

	return formModel as GenericModel;
}

export function createGeneratedLocationDocument(): GenericModel {
	const generatedDocument = structuredClone(loadFixtureModel(GENERATED_DOCUMENT_TEMPLATE_PATH)) as MutableFixtureModel;
	generatedDocument.header.id = LOCATION_GENERATED_DOCUMENT_ID;
	generatedDocument.header.modelVersion = DOCUMENT_MODEL_VERSION;

	if (isRecord(generatedDocument.content) && isRecord(generatedDocument.content.modelInfo)) {
		generatedDocument.content.modelInfo.name = LOCATION_GENERATED_DOCUMENT_ID;
	}

	return generatedDocument as GenericModel;
}

function annotationValue(model: MutableFixtureModel, name: string): string | undefined {
	return model.header.annotations?.find((annotation) => annotation.name === name)?.value;
}

function mergeSurvivingModels(
	initialModels: readonly FixtureModel[],
	addedModels: readonly FixtureModel[],
	updatedForm: FixtureModel,
	deletedIds: readonly string[]
): readonly FixtureModel[] {
	const deletedIdSet = new Set(deletedIds);
	const byId = new Map<string, FixtureModel>();

	for (const model of [...initialModels, ...addedModels, updatedForm]) {
		if (!deletedIdSet.has(model.header.id)) {
			byId.set(model.header.id, model);
		}
	}

	return [...byId.values()];
}

function withPath(model: FixtureModel): FixtureModel {
	return { ...model, path: `${model.header.id}.json` };
}

interface MutableFixtureModel {
	content?: unknown;
	header: {
		id: string;
		modelVersion?: string;
		annotations?: ModelAnnotation[];
		modelReferences?: ModelReference[];
	};
}

function isBindingConfiguration(value: unknown): value is BindingConfiguration {
	return isRecord(value) && (!isRecord(value.details) || typeof value.details.relationshipName === "string");
}

function isModelAnnotation(value: unknown): value is ModelAnnotation {
	return isRecord(value) && (value.name === undefined || typeof value.name === "string");
}

function isModelReference(value: unknown): value is ModelReference {
	return isRecord(value) && (value.reference === undefined || typeof value.reference === "string");
}
