/** RuM ID generated by extraction for the LocationBinding. */
export const LOCATION_RUM_ID = "BusinessPartner-form-binding-LocationBinding_RuM";

export const FIXTURE_PATHS = [
	"shared/relationship-models/Location.json",
	"shared/overview-models/Address-overview.json",
	"shared/overview-models/LocationLinks-overview.json",
	"shared/document-models/Address-document.json",
	"shared/document-models/BusinessPartner-document.json"
] as const;
const FORM_FIXTURE_PATH = "shared/form-models/BusinessPartner-form.json";
const GENERATED_DOCUMENT_TEMPLATE_PATH = "shared/document-models/ClaimLocation_location____generated.json";
const LOCATION_BINDING_NAME = "LocationBinding";

export interface FixtureModel extends IndexedModel {
	readonly header: IndexedModel["header"] & {
		readonly modelVersion?: string;
		readonly annotations?: readonly unknown[];
	};
	readonly content?: unknown;
}

export interface ModelReference {
	readonly purpose?: string;
	readonly modelType?: string;
	readonly reference?: string;
}

export interface ModelAnnotation {
	readonly name?: string;
	readonly value?: string;
}

export interface BindingConfiguration {
	readonly details?: { readonly name?: string; readonly relationshipName?: string };
}

export interface LocationExtractionResult {
	readonly workspaceModels: readonly FixtureModel[];
	readonly addedModels: readonly FixtureModel[];
	readonly updatedForm: FixtureModel;
	readonly rumModel: FixtureModel;
	readonly deletedIds: readonly string[];
	readonly index: ModelIndex<FixtureModel>;
	readonly survivingModels: readonly FixtureModel[];
	readonly findAddedById: (id: string) => FixtureModel | undefined;
	readonly findSurvivingById: (id: string) => FixtureModel | undefined;
}

/** Runs the Location DualPane fixture through extraction with the requested keepModels flag. */
export function runLocationExtraction(keepModels: boolean): LocationExtractionResult {
	const formModel = createLocationOnlyFormModel();
	const generatedDocument = createGeneratedLocationDocument();
	const workspaceModels = [...FIXTURE_PATHS.map(loadFixtureModel), formModel, generatedDocument].map(toFixtureModel);
	const harness = createFixtureContext({ models: workspaceModels, config: { keepModels } });
	const updatedForm = toFixtureModel(
		extractionTransform(formModel, { log: vi.fn(), info: vi.fn(), error: vi.fn() }, harness.context)
	);
	const addedModels = harness.getAddedModels().map(toFixtureModel);
	const deletedIds = harness.getDeletedIds();
	const survivingModels = mergeSurvivingModels(workspaceModels, addedModels, updatedForm, deletedIds);
	const index = buildModelIndex<FixtureModel>(survivingModels.map(withPath));
	const rumModel = requireModel(
		addedModels.find((model) => model.header.modelType === "relationship-ui"),
		"Location relationship-ui"
	);

	return {
		workspaceModels,
		addedModels,
		updatedForm,
		rumModel,
		deletedIds,
		index,
		survivingModels,
		findAddedById: (id) => addedModels.find((model) => model.header.id === id),
		findSurvivingById: (id) => survivingModels.find((model) => model.header.id === id)
	};
}

